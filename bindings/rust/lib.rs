//! This crate provides AQL language support for the [tree-sitter][] parsing library.
//!
//! Typically, you will use the [LANGUAGE][] constant to add this language to a
//! tree-sitter [Parser][], and then use the parser to parse some code:
//!
//! ```
//! let code = r#"
//! FOR d IN nodes
//!   FILTER d.kind == "belief"
//!   RETURN d
//! "#;
//! let mut parser = tree_sitter::Parser::new();
//! let language = tree_sitter_aql::LANGUAGE;
//! parser
//!     .set_language(&language.into())
//!     .expect("Error loading AQL parser");
//! let tree = parser.parse(code, None).unwrap();
//! assert!(!tree.root_node().has_error());
//! ```
//!
//! [Parser]: https://docs.rs/tree-sitter/*/tree_sitter/struct.Parser.html
//! [tree-sitter]: https://tree-sitter.github.io/

use tree_sitter_language::LanguageFn;

extern "C" {
    fn tree_sitter_aql() -> *const ();
}

/// The tree-sitter [`LanguageFn`][LanguageFn] for this grammar.
///
/// [LanguageFn]: https://docs.rs/tree-sitter-language/*/tree_sitter_language/struct.LanguageFn.html
pub const LANGUAGE: LanguageFn = unsafe { LanguageFn::from_raw(tree_sitter_aql) };

/// The content of the [`node-types.json`][] file for this grammar.
///
/// [`node-types.json`]: https://tree-sitter.github.io/tree-sitter/using-parsers/6-static-node-types
pub const NODE_TYPES: &str = include_str!("../../src/node-types.json");

/// The syntax highlighting query for this grammar (`queries/highlights.scm`).
pub const HIGHLIGHTS_QUERY: &str = include_str!("../../queries/highlights.scm");

// `KEYWORDS`: generated by `build.rs` from `src/grammar.json`.
include!(concat!(env!("OUT_DIR"), "/keywords.rs"));

#[cfg(test)]
mod tests {
    #[test]
    fn test_can_load_grammar() {
        let mut parser = tree_sitter::Parser::new();
        parser
            .set_language(&super::LANGUAGE.into())
            .expect("Error loading AQL parser");
    }

    #[test]
    fn parses_a_traversal_without_error() {
        let mut parser = tree_sitter::Parser::new();
        parser.set_language(&super::LANGUAGE.into()).unwrap();
        let code = "FOR v, e, p IN 1..3 OUTBOUND 'nodes/k1' GRAPH @graph \
                    PRUNE v.kind == 'leaf' OPTIONS { uniqueVertices: 'global' } \
                    SORT LENGTH(p.edges) DESC LIMIT 10 RETURN { v, e }";
        let tree = parser.parse(code, None).unwrap();
        assert!(
            !tree.root_node().has_error(),
            "{}",
            tree.root_node().to_sexp()
        );
    }

    #[test]
    fn keywords_cover_clauses_traversals_and_literals() {
        for kw in [
            "FOR",
            "RETURN",
            "FILTER",
            "COLLECT",
            "AGGREGATE",
            "OUTBOUND",
            "ANY",
            "NONE",
            "SHORTEST_PATH",
            "K_SHORTEST_PATHS",
            "ALL_SHORTEST_PATHS",
            "TRUE",
            "NULL",
            "AT",
        ] {
            assert!(super::KEYWORDS.contains(&kw), "missing {kw}");
        }
        assert!(
            super::KEYWORDS.windows(2).all(|w| w[0] < w[1]),
            "sorted, no duplicates"
        );
        assert!(super::KEYWORDS
            .iter()
            .all(|k| k.bytes().all(|b| b.is_ascii_uppercase() || b == b'_')));
    }

    #[test]
    fn highlights_query_compiles() {
        let language: tree_sitter::Language = super::LANGUAGE.into();
        tree_sitter::Query::new(&language, super::HIGHLIGHTS_QUERY)
            .expect("highlights.scm must compile against the grammar");
    }
}
